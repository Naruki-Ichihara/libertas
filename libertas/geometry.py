    @classmethod
    def rectangle(
        cls,
        width: float,
        height: float,
        mesh_size: float = 0.1,
        origin: tuple = (0.0, 0.0)
    ) -> "Geometry":
        """
        Create rectangular geometry (convenience method).

        Args:
            width: Width of rectangle
            height: Height of rectangle
            mesh_size: Mesh element size
            origin: Origin point (x, y)

        Returns:
            Geometry instance
        """
        nx = max(int(width / mesh_size), 2)
        ny = max(int(height / mesh_size), 2)

        mesh = pt.RectangleMesh(
            pt.MPI_Communicator.comm_world,
            pt.Point(origin[0], origin[1]),
            pt.Point(origin[0] + width, origin[1] + height),
            nx, ny
        )

        return cls(
            mesh,
            metadata={
                "source": "builtin",
                "shape": "rectangle",
                "width": width,
                "height": height
            }
        )

    @classmethod
    def box(
        cls,
        width: float,
        height: float,
        depth: float,
        mesh_size: float = 0.1,
        origin: tuple = (0.0, 0.0, 0.0)
    ) -> "Geometry":
        """
        Create box geometry (convenience method).

        Args:
            width: Width of box (x)
            height: Height of box (y)
            depth: Depth of box (z)
            mesh_size: Mesh element size
            origin: Origin point (x, y, z)

        Returns:
            Geometry instance
        """
        nx = max(int(width / mesh_size), 2)
        ny = max(int(height / mesh_size), 2)
        nz = max(int(depth / mesh_size), 2)

        mesh = pt.BoxMesh(
            pt.MPI_Communicator.comm_world,
            pt.Point(origin[0], origin[1], origin[2]),
            pt.Point(origin[0] + width, origin[1] + height, origin[2] + depth),
            nx, ny, nz
        )

        return cls(
            mesh,
            metadata={
                "source": "builtin",
                "shape": "box",
                "width": width,
                "height": height,
                "depth": depth
            }
        )

    def get_function_space(self, family: str, degree: int, vector: bool = False, dim: Optional[int] = None) -> Any:
        """
        Get or create function space on this mesh.

        Args:
            family: Element family (e.g., "CG", "DG")
            degree: Polynomial degree
            vector: Whether to create vector function space
            dim: Vector dimension (for vector spaces)

        Returns:
            FEniCS function space
        """
        key = f"{family}_{degree}_{'vector' if vector else 'scalar'}_{dim or ''}"

        if key not in self._function_spaces:
            if vector:
                if dim:
                    self._function_spaces[key] = pt.VectorFunctionSpace(
                        self.mesh, family, degree, dim=dim
                    )
                else:
                    self._function_spaces[key] = pt.VectorFunctionSpace(
                        self.mesh, family, degree
                    )
            else:
                self._function_spaces[key] = pt.FunctionSpace(self.mesh, family, degree)

        return self._function_spaces[key]

    def get_tensor_function_space(self, family: str, degree: int) -> Any:
        """
        Get or create tensor function space on this mesh.

        Args:
            family: Element family (e.g., "CG", "DG")
            degree: Polynomial degree

        Returns:
            FEniCS tensor function space
        """
        key = f"{family}_{degree}_tensor"

        if key not in self._function_spaces:
            self._function_spaces[key] = pt.TensorFunctionSpace(self.mesh, family, degree)

        return self._function_spaces[key]

    @property
    def dim(self) -> int:
        """Get spatial dimension of the geometry."""
        return self.mesh.geometry().dim()

    def save(self, filepath: str) -> None:
        """
        Save mesh to file.

        Args:
            filepath: Output file path (.xml, .xdmf)
        """
        filepath = Path(filepath)

        if filepath.suffix == ".xml":
            pt.File(str(filepath)) << self.mesh
        elif filepath.suffix == ".xdmf":
            pt.XDMFFile(str(filepath)).write(self.mesh)
        else:
            raise ValueError(f"Unsupported file format: {filepath.suffix}")
