"""Geometry and mesh handling for libertas."""

from typing import Optional, Dict, Any, Callable
from pathlib import Path
import numpy as np

try:
    from libertas.pytop import pytop as pt
except ImportError:
    from libertas import pytop as pt


class Geometry:
    """
    Unified geometry and mesh interface for topology optimization.

    Supports multiple mesh sources: pygmsh, gmsh files, FEniCS meshes,
    meshio, and fullcontrol paths.
    """

    def __init__(self, mesh: pt.Mesh, metadata: Optional[Dict[str, Any]] = None) -> None:
        """
        Initialize geometry with a FEniCS mesh.

        Args:
            mesh: FEniCS mesh object
            metadata: Optional metadata about the mesh (labels, physical groups, etc.)
        """
        self.mesh = mesh
        self.metadata = metadata or {}
        self._function_spaces: Dict[str, Any] = {}

    @classmethod
    def from_pygmsh(
        cls,
        pygmsh_mesh: Any,
        planation: bool = True,
        mpi_comm: Optional[Any] = None,
        save_path: Optional[str] = None
    ) -> "Geometry":
        """
        Create geometry from pygmsh mesh.

        Args:
            pygmsh_mesh: Mesh generated by pygmsh
            planation: Whether to apply planation
            mpi_comm: MPI communicator (default: MPI_Communicator)
            save_path: Optional path to save mesh as .xml

        Returns:
            Geometry instance
        """
        if mpi_comm is None:
            mpi_comm = pt.MPI_Communicator

        # Create directory for save_path if needed
        if save_path:
            save_path_obj = Path(save_path)
            save_path_obj.parent.mkdir(parents=True, exist_ok=True)

        mesh = pt.from_pygmsh(
            pygmsh_mesh,
            planation=planation,
            mpi_comm=mpi_comm,
            save_for=save_path
        )

        return cls(mesh, metadata={"source": "pygmsh"})

    @classmethod
    def from_file(cls, filepath: str) -> "Geometry":
        """
        Load geometry from mesh file (.xml, .xdmf, .msh).

        Args:
            filepath: Path to mesh file

        Returns:
            Geometry instance
        """
        filepath = Path(filepath)

        if not filepath.exists():
            raise FileNotFoundError(f"Mesh file not found: {filepath}")

        mesh = pt.Mesh(str(filepath))

        return cls(mesh, metadata={"source": "file", "filepath": str(filepath)})

    @classmethod
    def from_fenics(cls, fenics_mesh: pt.Mesh, metadata: Optional[Dict] = None) -> "Geometry":
        """
        Wrap existing FEniCS mesh.

        Args:
            fenics_mesh: FEniCS mesh object
            metadata: Optional metadata

        Returns:
            Geometry instance
        """
        return cls(fenics_mesh, metadata=metadata or {"source": "fenics"})

    @classmethod
    def from_meshio(cls, meshio_mesh: Any) -> "Geometry":
        """
        Create geometry from meshio mesh.

        Args:
            meshio_mesh: Mesh from meshio library

        Returns:
            Geometry instance
        """
        # Convert meshio to FEniCS format
        # This requires saving to temp file and loading
        import tempfile

        with tempfile.NamedTemporaryFile(suffix=".xdmf", delete=False) as tmp:
            tmp_path = tmp.name

        try:
            import meshio
            meshio.write(tmp_path, meshio_mesh)
            mesh = pt.Mesh(tmp_path)
        finally:
            Path(tmp_path).unlink(missing_ok=True)
            Path(tmp_path.replace(".xdmf", ".h5")).unlink(missing_ok=True)

        return cls(mesh, metadata={"source": "meshio"})

